use flate2::read::MultiGzDecoder;
use keyrill_windows_build::Digest;
use serde_json::{Value, json};
use std::collections::BTreeMap;
use std::error::Error;
use std::fs;
use std::io::Read;
use std::path::Path;

type Result<T> = std::result::Result<T, Box<dyn Error>>;

const SOURCE: &str = "model/data/model.inc.gz";
const SOURCE_BYTES: usize = 1_856_041;
const COMPRESSED_SHA: &str = "51692f3630db645b13057b9c55b9edb3ea69fba2887a2d3304786117fc238a1b";
const PLAINTEXT_SHA: &str = "82b22dd4055c4bdb703df8a81b1a15474b5b9be22a64525d416f53609381ac27";
const NOTICES: [&str; 2] = ["model-notice.txt", "wordfreq-code-license.txt"];
const HEADER: [&str; 3] = [
    "// Generated by tools/build_model.py; do not edit",
    "// Data derived from wordfreq 3.1.1 by Robyn Speer; CC-BY-SA-4.0",
    "// Keep data/model-notice.txt and its source attributions with derived data and binaries",
];

struct Language {
    name: &'static str,
    alphabet: Vec<char>,
    words: Vec<(String, i32)>,
    chain: Vec<i32>,
}

fn micro(text: &str) -> Result<i32> {
    let unsigned = text.strip_prefix('-').unwrap_or(text);
    let (whole, fraction) = unsigned.split_once('.').ok_or("malformed model number")?;
    if whole.is_empty()
        || !whole.bytes().all(|byte| byte.is_ascii_digit())
        || fraction.len() != 6
        || !fraction.bytes().all(|byte| byte.is_ascii_digit())
    {
        return Err("malformed model number".into());
    }
    let magnitude = whole
        .parse::<i64>()?
        .checked_mul(1_000_000)
        .and_then(|value| value.checked_add(fraction.parse::<i64>().ok()?))
        .ok_or("model number overflow")?;
    let signed = if text.starts_with('-') {
        -magnitude
    } else {
        magnitude
    };
    let value = i32::try_from(signed)?;
    if (f64::from(value) / 1_000_000.0).to_bits() != text.parse::<f64>()?.to_bits() {
        return Err("model value does not reconstruct exactly".into());
    }
    Ok(value)
}

fn expect(lines: &mut std::str::Split<'_, char>, expected: &str) -> Result<()> {
    if lines.next() != Some(expected) {
        return Err("unexpected model source grammar".into());
    }
    Ok(())
}

fn parse(text: &str, manifest: &Value) -> Result<Vec<Language>> {
    let mut lines = text.split('\n');
    for line in HEADER {
        expect(&mut lines, line)?;
    }
    let mut languages = Vec::new();
    for name in ["en", "ru"] {
        let metadata = &manifest["languages"][name];
        let alphabet: Vec<_> = metadata["alphabet"]
            .as_str()
            .ok_or("model alphabet missing")?
            .chars()
            .collect();
        if alphabet.is_empty()
            || alphabet.len() > 256
            || alphabet.iter().any(|letter| letter.len_utf16() != 1)
        {
            return Err("model alphabet outside format bounds".into());
        }
        expect(
            &mut lines,
            &format!("static const FrequencyEntry {name}Words[] = {{"),
        )?;
        let mut words: Vec<(String, i32)> = Vec::new();
        loop {
            let line = lines.next().ok_or("model word table truncated")?;
            if line == "};" {
                break;
            }
            let entry = line
                .strip_prefix("  {u\"")
                .and_then(|value| value.strip_suffix("},"))
                .ok_or("malformed model word entry")?;
            let (word, value) = entry
                .split_once("\", ")
                .ok_or("malformed model word entry")?;
            if !(1..=32).contains(&word.chars().count())
                || word
                    .chars()
                    .any(|letter| matches!(letter, '"' | '\\') || !alphabet.contains(&letter))
                || words
                    .last()
                    .is_some_and(|(previous, _)| previous.as_str() >= word)
            {
                return Err("model word outside sorted alphabet bounds".into());
            }
            words.push((word.to_owned(), micro(value)?));
        }
        if Some(words.len() as u64) != metadata["words"].as_u64() {
            return Err("model word count differs from manifest".into());
        }
        expect(
            &mut lines,
            &format!("static const double {name}Chain[] = {{"),
        )?;
        let mut chain = Vec::new();
        loop {
            let line = lines.next().ok_or("model chain table truncated")?;
            if line == "};" {
                break;
            }
            let number = line
                .strip_prefix("  ")
                .and_then(|value| value.strip_suffix(','))
                .ok_or("malformed model chain entry")?;
            chain.push(micro(number)?);
        }
        if chain.len() != (alphabet.len() + 2).pow(3) {
            return Err("model chain count differs from alphabet".into());
        }
        languages.push(Language {
            name,
            alphabet,
            words,
            chain,
        });
    }
    expect(&mut lines, "")?;
    if lines.next().is_some() {
        return Err("model source has trailing content".into());
    }
    Ok(languages)
}

fn push_u32(output: &mut Vec<u8>, value: usize) -> Result<()> {
    output.extend(u32::try_from(value)?.to_le_bytes());
    Ok(())
}

fn pack(languages: &[Language], source: &[u8]) -> Result<Vec<u8>> {
    let mut output = b"KRMODEL\0".to_vec();
    output.extend(1_u32.to_le_bytes());
    output.extend(Digest::of_bytes(source).bytes());
    push_u32(&mut output, languages.len())?;
    for language in languages {
        push_u32(&mut output, language.alphabet.len())?;
        for &letter in &language.alphabet {
            output.extend((letter as u16).to_le_bytes());
        }
        push_u32(&mut output, language.words.len())?;
        let mut encoded = Vec::new();
        let mut offsets = vec![0];
        for (word, _) in &language.words {
            for letter in word.chars() {
                let index = language
                    .alphabet
                    .iter()
                    .position(|&candidate| candidate == letter)
                    .ok_or("model word encoding failed")?;
                encoded.push(u8::try_from(index)?);
            }
            offsets.push(encoded.len());
        }
        for offset in offsets {
            push_u32(&mut output, offset)?;
        }
        output.extend(encoded);
        for &value in language
            .words
            .iter()
            .map(|(_, value)| value)
            .chain(&language.chain)
        {
            output.extend(value.to_le_bytes());
        }
    }
    Ok(output)
}

fn build(root: &Path) -> Result<BTreeMap<&'static str, Vec<u8>>> {
    let compressed = fs::read(root.join(SOURCE))?;
    if compressed.len() != SOURCE_BYTES
        || Digest::of_bytes(&compressed).to_string() != COMPRESSED_SHA
    {
        return Err("compressed model source differs from frozen artifact".into());
    }
    let mut source = Vec::new();
    MultiGzDecoder::new(compressed.as_slice()).read_to_end(&mut source)?;
    if Digest::of_bytes(&source).to_string() != PLAINTEXT_SHA {
        return Err("plaintext model source differs from frozen artifact".into());
    }
    let manifest: Value =
        serde_json::from_slice(&fs::read(root.join("model/data/model-manifest.json"))?)?;
    if manifest["model_sha256"] != PLAINTEXT_SHA {
        return Err("model manifest names a different model".into());
    }
    let languages = parse(std::str::from_utf8(&source)?, &manifest)?;
    let model = pack(&languages, &source)?;
    let mut outputs = BTreeMap::new();
    for notice in NOTICES {
        outputs.insert(notice, fs::read(root.join("model/data").join(notice))?);
    }
    let language_metadata: BTreeMap<_, _> = languages
        .iter()
        .map(|language| {
            (
                language.name,
                json!({
                    "alphabet": language.alphabet.iter().collect::<String>(),
                    "chain_values": language.chain.len(),
                    "words": language.words.len(),
                }),
            )
        })
        .collect();
    let provenance = json!({
        "format": {"magic": "KRMODEL", "version": 1},
        "languages": language_metadata,
        "license": manifest["license"],
        "notices": NOTICES,
        "output": {"bytes": model.len(), "sha256": Digest::of_bytes(&model).to_string()},
        "packer_sha256": Digest::of_bytes(&fs::read(root.join("tools/pack-model.py"))?).to_string(),
        "source": {"compressed_sha256": COMPRESSED_SHA, "path": SOURCE, "plaintext_sha256": PLAINTEXT_SHA},
        "value_scale": 1_000_000,
        "values_reconstructed_exactly": languages.iter().map(|language| language.words.len() + language.chain.len()).sum::<usize>(),
    });
    let mut bytes = serde_json::to_vec_pretty(&provenance)?;
    bytes.push(b'\n');
    outputs.insert("model-provenance.json", bytes);
    outputs.insert("model.bin", model);
    Ok(outputs)
}

pub(crate) fn check(root: &Path) -> Result<()> {
    for (name, expected) in build(root)? {
        if fs::read(root.join("assets").join(name))? != expected {
            return Err(format!("stale model asset {name}").into());
        }
    }
    println!("Frozen model, provenance and notices regenerate byte-for-byte.");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn source() -> (String, Value) {
        let mut text = HEADER.join("\n") + "\n";
        for name in ["en", "ru"] {
            text.push_str(&format!("static const FrequencyEntry {name}Words[] = {{\n  {{u\"a\", -1.250000}},\n}};\nstatic const double {name}Chain[] = {{\n"));
            text.push_str(&"  -0.125000,\n".repeat(27));
            text.push_str("};\n");
        }
        (
            text,
            json!({"languages": {"en": {"alphabet": "a", "words": 1}, "ru": {"alphabet": "a", "words": 1}}}),
        )
    }

    #[test]
    fn decimal_values_match_exact_floating_point_parse() {
        for (text, expected) in [
            ("-1.250000", -1_250_000),
            ("0.000001", 1),
            ("2147.483647", i32::MAX),
            ("-2147.483648", i32::MIN),
        ] {
            assert_eq!(micro(text).unwrap(), expected);
        }
        for text in [
            "-0.000000",
            "2147.483648",
            "-2147.483649",
            "1.0",
            "+1.000000",
            "1.0000000",
            ".000001",
            "1e1.000000",
            " 1.000000",
        ] {
            assert!(micro(text).is_err(), "{text}");
        }
    }

    #[test]
    fn parser_requires_complete_exact_grammar_and_manifest_counts() {
        let (text, manifest) = source();
        let languages = parse(&text, &manifest).unwrap();
        assert_eq!(languages.len(), 2);
        assert_eq!(languages[0].words, [("a".to_owned(), -1_250_000)]);
        assert_eq!(languages[1].chain, [-125_000; 27]);
        for malformed in [
            text.trim_end().to_owned(),
            text.clone() + "\n",
            text.replacen("-1.250000", "-1.25", 1),
            text.replacen("u\"a\"", "u\"b\"", 1),
            text.replacen("  -0.125000,\n", "", 1),
        ] {
            assert!(parse(&malformed, &manifest).is_err());
        }
        let mut bad_manifest = manifest;
        bad_manifest["languages"]["en"]["words"] = json!(2);
        assert!(parse(&text, &bad_manifest).is_err());
    }

    #[test]
    fn binary_format_has_literal_layout_and_values() {
        let (text, manifest) = source();
        let languages = parse(&text, &manifest).unwrap();
        let bytes = pack(&languages, b"abc").unwrap();
        let mut expected = b"KRMODEL\0".to_vec();
        expected.extend(1_u32.to_le_bytes());
        expected.extend([
            0xba, 0x78, 0x16, 0xbf, 0x8f, 0x01, 0xcf, 0xea, 0x41, 0x41, 0x40, 0xde, 0x5d, 0xae,
            0x22, 0x23, 0xb0, 0x03, 0x61, 0xa3, 0x96, 0x17, 0x7a, 0x9c, 0xb4, 0x10, 0xff, 0x61,
            0xf2, 0x00, 0x15, 0xad,
        ]);
        expected.extend(2_u32.to_le_bytes());
        for _ in 0..2 {
            expected.extend(1_u32.to_le_bytes());
            expected.extend(97_u16.to_le_bytes());
            expected.extend(1_u32.to_le_bytes());
            expected.extend(0_u32.to_le_bytes());
            expected.extend(1_u32.to_le_bytes());
            expected.push(0);
            expected.extend((-1_250_000_i32).to_le_bytes());
            for _ in 0..27 {
                expected.extend((-125_000_i32).to_le_bytes());
            }
        }
        assert_eq!(bytes, expected);
    }
}
