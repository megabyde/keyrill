#!/usr/bin/env python3
"""Pack the frozen reference model into assets/model.bin.

Build-only and offline, standard library only. Reads the hash-pinned frozen artifact
model/data/model.inc.gz, validates its exact grammar, and writes
deterministic assets: model.bin, model-provenance.json and byte copies of the data notices.
With --check, regenerates in memory and fails if any tracked asset differs.

model.bin layout, all integers little-endian:
  b"KRMODEL\\0", u32 version, 32-byte SHA-256 of the plaintext source, u32 language count,
  then per language (en, ru):
    u32 alphabet length, u16[] alphabet units,
    u32 word count n, u32[n + 1] word offsets, u8[] alphabet indices of each word,
    i32[n] log10 frequencies, i32[(alphabet length + 2) ** 3] log10 chain probabilities.
Every value is the source's six-decimal text times 10**6, so value / 1e6 reproduces the
correctly rounded parse of that text exactly.
"""

import argparse
import gzip
import hashlib
import json
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE_DIR = Path("model/data")
SOURCE = SOURCE_DIR / "model.inc.gz"
SOURCE_SHA256 = "82b22dd4055c4bdb703df8a81b1a15474b5b9be22a64525d416f53609381ac27"
SOURCE_COMPRESSED_SHA256 = "51692f3630db645b13057b9c55b9edb3ea69fba2887a2d3304786117fc238a1b"
SOURCE_COMPRESSED_BYTES = 1_856_041
NOTICES = ("model-notice.txt", "wordfreq-code-license.txt")
ASSETS = Path("assets")
MAGIC = b"KRMODEL\0"
VERSION = 1
HEADER = (
    "// Generated by tools/build_model.py; do not edit",
    "// Data derived from wordfreq 3.1.1 by Robyn Speer; CC-BY-SA-4.0",
    "// Keep data/model-notice.txt and its source attributions with derived data and binaries",
)
WORD = re.compile(r'  \{u"([^"\\]+)", (-?\d+\.\d{6})\},')
NUMBER = re.compile(r"  (-?\d+\.\d{6}),")
MAX_WORD = 32


class PackError(Exception):
    pass


def micro(text):
    whole, fraction = text.lstrip("-").split(".")
    value = int(whole) * 1_000_000 + int(fraction)
    value = -value if text.startswith("-") else value
    if not -(2**31) <= value < 2**31:
        raise PackError("value out of i32 range")
    # Both sides are correctly rounded, so this holds for every six-decimal value; checking it
    # per value keeps the claim falsifiable instead of assumed.
    if struct.pack("<d", value / 1_000_000) != struct.pack("<d", float(text)):
        raise PackError("value does not reconstruct exactly")
    return value


def parse(text, manifest):
    lines = text.split("\n")
    if lines[-1] != "":
        raise PackError("source does not end with a newline")
    lines.pop()
    if tuple(lines[: len(HEADER)]) != HEADER:
        raise PackError("unexpected source header")
    position = len(HEADER)

    def expect(line):
        nonlocal position
        if position >= len(lines) or lines[position] != line:
            raise PackError(f"line {position + 1}: expected {line!r}")
        position += 1

    languages = []
    for name in ("en", "ru"):
        alphabet = manifest["languages"][name]["alphabet"]
        expect(f"static const FrequencyEntry {name}Words[] = {{")
        words, previous = [], None
        while position < len(lines) and lines[position] != "};":
            match = WORD.fullmatch(lines[position])
            if not match:
                raise PackError(f"line {position + 1}: malformed word entry")
            word = match[1]
            if not 1 <= len(word) <= MAX_WORD or any(c not in alphabet for c in word):
                raise PackError(f"line {position + 1}: word outside alphabet or length bounds")
            if previous is not None and word <= previous:
                raise PackError(f"line {position + 1}: words not strictly increasing")
            words.append((word, micro(match[2])))
            previous = word
            position += 1
        expect("};")
        if len(words) != manifest["languages"][name]["words"]:
            raise PackError(f"{name}: word count differs from manifest")
        expect(f"static const double {name}Chain[] = {{")
        chain = []
        while position < len(lines) and lines[position] != "};":
            match = NUMBER.fullmatch(lines[position])
            if not match:
                raise PackError(f"line {position + 1}: malformed chain entry")
            chain.append(micro(match[1]))
            position += 1
        expect("};")
        if len(chain) != (len(alphabet) + 2) ** 3:
            raise PackError(f"{name}: chain size differs from alphabet")
        languages.append((name, alphabet, words, chain))
    if position != len(lines):
        raise PackError(f"line {position + 1}: trailing content")
    return languages


def pack(languages, source_sha256):
    out = bytearray(MAGIC)
    out += struct.pack("<I", VERSION) + bytes.fromhex(source_sha256)
    out += struct.pack("<I", len(languages))
    for _, alphabet, words, chain in languages:
        units = alphabet.encode("utf-16-le")
        out += struct.pack("<I", len(units) // 2) + units
        out += struct.pack("<I", len(words))
        offsets, blob = [0], bytearray()
        for word, _ in words:
            blob += bytes(alphabet.index(c) for c in word)
            offsets.append(len(blob))
        out += struct.pack(f"<{len(offsets)}I", *offsets) + blob
        out += struct.pack(f"<{len(words)}i", *(value for _, value in words))
        out += struct.pack(f"<{len(chain)}i", *chain)
    return bytes(out)


def build():
    with (ROOT / SOURCE).open("rb") as source:
        compressed = source.read(SOURCE_COMPRESSED_BYTES + 1)
    if len(compressed) != SOURCE_COMPRESSED_BYTES or hashlib.sha256(compressed).hexdigest() != SOURCE_COMPRESSED_SHA256:
        raise PackError("compressed source differs from the frozen artifact")
    text_bytes = gzip.decompress(compressed)
    plaintext_sha256 = hashlib.sha256(text_bytes).hexdigest()
    if plaintext_sha256 != SOURCE_SHA256:
        raise PackError(f"source plaintext SHA-256 {plaintext_sha256} is not {SOURCE_SHA256}")
    manifest = json.loads((ROOT / SOURCE_DIR / "model-manifest.json").read_text("utf-8"))
    if manifest["model_sha256"] != SOURCE_SHA256:
        raise PackError("model manifest names a different model")
    languages = parse(text_bytes.decode("utf-8"), manifest)
    model = pack(languages, plaintext_sha256)
    outputs = {"model.bin": model}
    for notice in NOTICES:
        outputs[notice] = (ROOT / SOURCE_DIR / notice).read_bytes()
    provenance = {
        "format": {"magic": MAGIC.decode("ascii").rstrip("\0"), "version": VERSION},
        "languages": {
            name: {"alphabet": alphabet, "chain_values": len(chain), "words": len(words)}
            for name, alphabet, words, chain in languages
        },
        "license": manifest["license"],
        "notices": list(NOTICES),
        "output": {"bytes": len(model), "sha256": hashlib.sha256(model).hexdigest()},
        "packer_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "source": {
            "compressed_sha256": hashlib.sha256(compressed).hexdigest(),
            "path": SOURCE.as_posix(),
            "plaintext_sha256": plaintext_sha256,
        },
        "value_scale": 1_000_000,
        "values_reconstructed_exactly": sum(len(w) + len(c) for _, _, w, c in languages),
    }
    outputs["model-provenance.json"] = (
        json.dumps(provenance, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    ).encode("utf-8")
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()
    try:
        outputs = build()
    except (OSError, ValueError, KeyError, PackError) as error:
        print(f"pack-model: {error}", file=sys.stderr)
        return 1
    stale = []
    for name, data in outputs.items():
        path = ROOT / ASSETS / name
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                stale.append(name)
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_bytes(data)
    if stale:
        print(f"pack-model: stale assets: {', '.join(stale)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
