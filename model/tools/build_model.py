import hashlib
import importlib.metadata
import json
import math
from pathlib import Path
import platform

import wordfreq


ROOT = Path(__file__).resolve().parents[1]
ALPHABETS = {"en": "abcdefghijklmnopqrstuvwxyz", "ru": "абвгдеёжзийклмнопрстуфхцчшщъыьэюя"}
MINIMUM_FREQUENCY = 1e-7
VIRTUAL_TOKENS = 2_000_000
SMOOTHING = 0.1


def literal(word):
    return 'u"' + word + '"'


def main():
    if importlib.metadata.version("wordfreq") != "3.1.1":
        raise RuntimeError("wordfreq 3.1.1 is required")
    data = ROOT / "data"
    package = importlib.metadata.distribution("wordfreq")
    metadata = package.read_text("METADATA")
    notice = (
        "Keyrill frequency and character-model data\n"
        "Derived from wordfreq 3.1.1 by Robyn Speer; modified by the build_model.py generator.\n"
        "Source: https://github.com/rspeer/wordfreq\n"
        "Derived data: Creative Commons Attribution-ShareAlike 4.0.\n"
        "License: https://creativecommons.org/licenses/by-sa/4.0/\n"
        "SUBTLEX is freely available data; credit Marc Brysbaert and the authors listed below.\n\n"
        + metadata[metadata.index("## License"):]
    )
    (data / "model-notice.txt").write_text(notice, encoding="utf-8")
    (data / "wordfreq-code-license.txt").write_text(package.read_text("LICENSE.txt"), encoding="utf-8")
    manifest = {
        "schema": 1,
        "source": "wordfreq 3.1.1 large lists",
        "license": "CC-BY-SA-4.0",
        "notice": "model-notice.txt",
        "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "requirements_sha256": hashlib.sha256(
            (ROOT / "tools/model-requirements.txt").read_bytes()
        ).hexdigest(),
        "python_version": platform.python_version(),
        "packages": {name: importlib.metadata.version(name) for name in
                     ("wordfreq", "msgpack", "langcodes", "ftfy", "regex", "locate", "wcwidth")},
        "minimum_frequency": MINIMUM_FREQUENCY,
        "maximum_word_length": 32,
        "preprocessing": "Exact lowercase alphabet membership; no Unicode normalization or retokenization",
        "model": "Order-2 character chain with start/end markers and additive smoothing",
        "virtual_tokens": VIRTUAL_TOKENS,
        "smoothing": SMOOTHING,
        "warning": "Corpus probabilities are not calibrated layout-error probabilities",
        "languages": {},
    }
    lines = [
        "// Generated by tools/build_model.py; do not edit",
        "// Data derived from wordfreq 3.1.1 by Robyn Speer; CC-BY-SA-4.0",
        "// Keep data/model-notice.txt and its source attributions with derived data and binaries",
    ]
    short = {
        "license": "CC-BY-SA-4.0", "notice": notice,
        "scope": "All retained source words of length 1-3 with defined physical mapping",
        "frequency_semantics": "wordfreq corpus estimates, not layout-error probabilities",
        "mapped_zero": "Absent from the full source list; not an assertion of zero probability",
        "pairs": [],
    }
    maps = dict(zip("qwertyuiop[]asdfghjkl;'zxcvbnm,.", "йцукенгшщзхъфывапролджэячсмитьбю"))
    tables = {}
    full_frequencies = {}
    for lang, alphabet in ALPHABETS.items():
        frequencies = wordfreq.get_frequency_dict(lang, wordlist="large")
        full_frequencies[lang] = frequencies
        words = {
            word: frequency for word, frequency in frequencies.items()
            if frequency >= MINIMUM_FREQUENCY and 1 <= len(word) <= 32
            and all(char in alphabet for char in word)
        }
        tables[lang] = words
        size = len(alphabet) + 2
        end, start = len(alphabet), len(alphabet) + 1
        counts = [0.0] * (size * size * size)
        totals = [0.0] * (size * size)
        for word, frequency in sorted(words.items()):
            a, b = start, start
            for c in [alphabet.index(char) for char in word] + [end]:
                weight = frequency * VIRTUAL_TOKENS
                counts[(a * size + b) * size + c] += weight
                totals[a * size + b] += weight
                a, b = b, c
        lines.append(f"static const FrequencyEntry {lang}Words[] = {{")
        for word, frequency in sorted(words.items()):
            lines.append(f"  {{{literal(word)}, {math.log10(frequency):.6f}}},")
        lines.append("};")
        lines.append(f"static const double {lang}Chain[] = {{")
        for i, count in enumerate(counts):
            probability = (count + SMOOTHING) / (totals[i // size] + SMOOTHING * (len(alphabet) + 1))
            lines.append(f"  {math.log10(probability):.6f},")
        lines.append("};")
        package_file = Path(wordfreq.__file__).parent / "data" / f"large_{lang}.msgpack.gz"
        manifest["languages"][lang] = {
            "alphabet": alphabet,
            "words": len(words),
            "retained_probability_mass": sum(words.values()),
            "source_sha256": hashlib.sha256(package_file.read_bytes()).hexdigest(),
        }
    for lang, words in tables.items():
        mapping = maps if lang == "en" else {v: k for k, v in maps.items()}
        mapping["\\" if lang == "en" else "ё"] = "ё" if lang == "en" else "\\"
        other = "ru" if lang == "en" else "en"
        for word, frequency in sorted(words.items()):
            if len(word) <= 3 and all(char in mapping for char in word):
                mapped = "".join(mapping[char] for char in word)
                short["pairs"].append({
                    "language": lang, "word": word, "mapped": mapped,
                    "frequency": frequency,
                    "mapped_frequency": full_frequencies[other].get(mapped, 0.0),
                })
    output = "\n".join(lines) + "\n"
    (data / "model.inc").write_text(output, encoding="utf-8")
    (data / "short-words.json").write_text(
        json.dumps(short, ensure_ascii=False, sort_keys=True, indent=2) + "\n", encoding="utf-8"
    )
    manifest["short_word_pairs"] = len(short["pairs"])
    manifest["model_sha256"] = hashlib.sha256(output.encode()).hexdigest()
    (data / "model-manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, sort_keys=True, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(manifest, ensure_ascii=False))


if __name__ == "__main__":
    main()
